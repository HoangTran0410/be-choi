/**
 * What every robot plays, in the pattern language documented on `parseBars` (groove.ts).
 *
 * Each robot has, for each of the five songs' drum feels, three patterns of rising busyness:
 *   1 = easy (a few long, calm notes), 2 = medium (the real part), 3 = busy (the whole arrangement
 *   with fills, ghost notes and ornaments).
 * All are four bars long so a part can tell a story over the loop: call (bar 1), answer (bar 2),
 * call again (bar 3) and a different ending (bar 4), with a fill or a pick-up into the next lap.
 * Velocity (`@1`…`@9`) marks strong and weak beats. Nothing here names a pitch: notes are written
 * against the bar's chord or the key's pentatonic scale, so they can never be wrong.
 *
 * The four chord progressions the parts are written against (see SONGS):
 *   pop    C  Am  F  G      disco  Bm  G  D  A      soft   F  C  Dm  Bb
 *   latin  Am7 D7 Gmaj7 Em7   east   A6 F#m7 Dsus2 Esus2
 */
import type { DrumStyle } from './groove';

export type Trio = readonly [string, string, string];
export type RobotPatterns = Record<DrumStyle, Trio>;

/** Join four bars. */
const b4 = (a: string, b: string, c: string, d: string): string => `${a} | ${b} | ${c} | ${d}`;
/** Three identical bars and a different last one (the fill or turnaround). */
const fill = (body: string, last: string): string => b4(body, body, body, last);

